"""requirements-release.txt — залежнасці зборкі exe і лаўнчара з версіямі і хэшамі.

Бярэ ўсталяванае ў гэтым venv (тое, з чым зборку праверылі), ідзе па залежнасцях ад
коранёў ROOTS і для кожнага пакета піша версію і sha256 усіх файлаў гэтай версіі на PyPI.
pyooz — не адсюль: кола збіраем самі (рэліз pyooz-0.0.8.<n>, core/belloc/oodle.py).

    python installer/lock.py            # перапісаць requirements-release.txt
    pip install --require-hashes -r requirements-release.txt   # чысты venv для зборкі рэліза
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request
from importlib import metadata

from packaging.markers import default_environment
from packaging.requirements import Requirement

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "requirements-release.txt")
# pyproject.toml: залежнасць ядра + extras unity, glacier, unreal, telltale, launcher, release
ROOTS = ["pycryptodome", "UnityPy", "numpy", "Pillow", "fonttools", "lz4", "texture2ddecoder",
         "etcpak", "opencv-python-headless", "PySide6-Essentials", "pyinstaller"]
SKIP = {"pyooz"}


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def closure() -> dict[str, str]:
    """{імя: версія} — карані і ўсё, што ім патрэбна пад гэтай Python і Windows."""
    env = default_environment()
    found, todo = {}, list(ROOTS)
    while todo:
        name = norm(todo.pop())
        if name in found or name in SKIP:
            continue
        dist = metadata.distribution(name)
        found[name] = dist.version
        for r in dist.requires or []:
            req = Requirement(r)
            if req.marker is None or req.marker.evaluate({**env, "extra": ""}):
                todo.append(req.name)
    return dict(sorted(found.items()))


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "belloc-lock"}), timeout=30) as r:
        files = json.load(r)["urls"]
    if not files:
        raise SystemExit(f"{name}=={version}: на PyPI няма файлаў")
    return sorted(f["digests"]["sha256"] for f in files)


def main() -> int:
    pins = closure()
    # толькі ASCII: pip на Windows чытае гэты файл у cp1252
    lines = ["# Build dependencies for the exe installers and the launcher, pinned with hashes.",
             "# Generated by installer/lock.py from a tested venv; do not edit by hand.",
             "# pip install --require-hashes -r requirements-release.txt",
             "# pyooz is not here: we build its wheel ourselves (core/belloc/oodle.py).",
             f"# Python {sys.version_info.major}.{sys.version_info.minor}, Windows x64.", ""]
    for name, version in pins.items():
        lines.append(f"{name}=={version} \\")
        hs = hashes(name, version)
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{OUT}: {len(pins)} пакетаў")
    return 0


if __name__ == "__main__":
    sys.exit(main())
