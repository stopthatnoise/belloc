#!/usr/bin/env python3
"""Арфаграфічныя праверкі беларускага тэксту без слоўніка.

Ловяць спалучэнні, немагчымыя ў афіцыйным правапісе, — іх не знойдзе
праверка па слоўніку, калі памылка у ўласнай назве ці ў новым слове:

  * д/т перад і/е/ё/ю/я — дзеканне і цеканне: дзі/дзе/дзё/дзю/дзя,
    ці/це/цё/цю/ця (або цвёрдыя ды/дэ/до/ду/да, ты/тэ/то/ту/та);
  * р, ж, ш, ч перад і/е/ё/ю/я — зацвярдзенне: ры/рэ/ро/ру/ра,
    жы/жэ/жо/жу/жа і г. д.;
  * «й» пасля зычнай і «йа»/«йя» (пішацца «я»);
  * тры і болей «о» ў слове: пад націскам «о» бывае адно, а два
    звычайна азначаюць склад (водаправод, трохвугольнік).

Гэта не вердыкт: уласныя назвы і асобныя запазычанні могуць быць
выключэннем — іх дадаюць у белы спіс (`lint_allow.txt`).

    python -X utf8 -m belloc.lint --text файл --checks ortho
"""
from __future__ import annotations

import re

CYR_WORD_RE = re.compile(r"[А-Яа-яЁёІіЎў][А-Яа-яЁёІіЎў'’\-]*")
CONSONANTS = "бвгджзклмнпрстфхцчшў"

# мяккі галосны пасля цвёрдай зычнай → як пішацца
_SOFT = {
    "д": {"і": "дзі", "е": "дзе", "ё": "дзё", "ю": "дзю", "я": "дзя"},
    "т": {"і": "ці", "е": "це", "ё": "цё", "ю": "цю", "я": "ця"},
    "р": {"і": "ры", "е": "рэ", "ё": "ро", "ю": "ру", "я": "ра"},
    "ж": {"і": "жы", "е": "жэ", "ё": "жо", "ю": "жу", "я": "жа"},
    "ш": {"і": "шы", "е": "шэ", "ё": "шо", "ю": "шу", "я": "ша"},
    "ч": {"і": "чы", "е": "чэ", "ё": "чо", "ю": "чу", "я": "ча"},
}
# цвёрды варыянт для д/т: замест дзекання/цекання
_HARD_VOWEL = {"і": "ы", "е": "э", "ё": "о", "ю": "у", "я": "а"}
_SPECIAL = {"йа": "я", "йя": "я"}

_YOT_AFTER_CONS = re.compile(rf"[{CONSONANTS}]й")
_VOWELS = "аеёіоуыэюя"


def _parts(word: str) -> list[str]:
    return [p for p in re.split(r"[-'’]", word) if p]


def word_problems(word: str) -> list[str]:
    """Праблемы аднаго слова (можа быць з дэфісам ці апострафам)."""
    out: list[str] = []
    seen: set[str] = set()

    def add(msg: str):
        if msg not in seen:
            seen.add(msg)
            out.append(msg)

    for raw in _parts(word):
        low = raw.lower()
        # кароткія абрэвіятуры (ШІ, БРДМ) правапісных спалучэнняў не трымаюць
        if not (len(raw) <= 4 and raw.isupper()):
            for i in range(len(low) - 1):
                bg = low[i:i + 2]
                fix = _SOFT.get(bg[0], {}).get(bg[1])
                if fix:
                    alt = ""
                    if bg[0] in "дт":
                        alt = f" (або «{bg[0]}{_HARD_VOWEL[bg[1]]}»)"
                    add(f"«{bg}» — немагчымае спалучэнне, трэба «{fix}»{alt}")
                elif bg in _SPECIAL and (i == 0 or low[i - 1] in _VOWELS):
                    add(f"«{bg}» — немагчымае спалучэнне, трэба «{_SPECIAL[bg]}»")
            for m in _YOT_AFTER_CONS.finditer(low):
                add(f"«{m.group()}» — «й» пасля зычнай немагчымы")
        # два «о» — звычайна склад слова (водаправод, трохвугольнік), таму
        # ловім толькі відавочнае: тры і болей
        if low.count("о") >= 3 and not raw.isupper():
            add(f"«{raw}»: {low.count('о')} літары «о» — пад націскам бывае адно")
    return out


def text_problems(text: str) -> list[str]:
    """Праблемы ўсіх беларускіх слоў у тэксце, без паўтораў."""
    out: list[str] = []
    for w in CYR_WORD_RE.findall(text):
        for msg in word_problems(w):
            if msg not in out:
                out.append(msg)
    return out
